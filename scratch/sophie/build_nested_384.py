"""One purpose: derive the 384 nested validation cache from the 512 one.

The 512 cache at I:\\.cache\\wd-tagger-trainer\\valid_nested was built from the val tars and cannot
be regenerated by any script in the repo any more, but the 384 arms need the same 50000 images
at the same size to be scored by wdtag.validate. Downsampling keeps the images, their order and
their labels identical, which is what makes the 384 and 512 numbers comparable; the only cost is
one extra bilinear resample (source to 512, then 512 to 384).

    python scratch/sophie/build_nested_384.py

Writes images.npy, labels.npz and meta.json into the 384 cache tree. Refuses to overwrite.
"""

import json
import os
import shutil

import numpy as np
import torch
from torch.nn import functional as F

SRC = r"I:\.cache\wd-tagger-trainer\valid_nested"
DST = r"I:\.cache\wd-tagger-trainer-384\valid_nested"
SIZE = 384
CHUNK = 64


def main() -> None:
    os.makedirs(DST, exist_ok=True)
    dst_img = os.path.join(DST, "images.npy")
    if os.path.exists(dst_img):
        raise SystemExit(f"{dst_img} already exists; delete it to rebuild")

    meta = json.load(open(os.path.join(SRC, "meta.json"), encoding="utf-8"))
    total, size = int(meta["count"]), int(meta["size"])
    src = np.load(os.path.join(SRC, "images.npy"), mmap_mode="r")
    assert src.shape == (total, 3, size, size), src.shape

    out = np.lib.format.open_memmap(dst_img, mode="w+", dtype=np.uint8,
                                    shape=(total, 3, SIZE, SIZE))
    for start in range(0, total, CHUNK):
        stop = min(start + CHUNK, total)
        x = torch.from_numpy(np.ascontiguousarray(src[start:stop])).float()
        x = F.interpolate(x, size=(SIZE, SIZE), mode="bilinear",
                          align_corners=False, antialias=True)
        out[start:stop] = x.clamp(0, 255).round().to(torch.uint8).numpy()
        if start % (CHUNK * 100) == 0:
            print(f"{stop}/{total}", flush=True)
    out.flush()
    del out

    shutil.copyfile(os.path.join(SRC, "labels.npz"), os.path.join(DST, "labels.npz"))
    meta["size"] = SIZE
    json.dump(meta, open(os.path.join(DST, "meta.json"), "w", encoding="utf-8"), indent=2)
    print("wrote", DST, "count", total, "size", SIZE)


if __name__ == "__main__":
    main()
